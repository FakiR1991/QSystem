    private void selectClickedItem(MouseEvent e) {
        if (SwingUtilities.isRightMouseButton(e)) {
            JList list = (JList)e.getSource();
            int row = list.locationToIndex(e.getPoint());
            list.setSelectedIndex(row);
        }
    }
    
    private void removeSession(QSession session) {
        if (JOptionPane.showConfirmDialog(this,
                            "<html>Уверены, что хотите удалить сессию " + session.toString().replace("<html>", "").replace("</html>", "") + "?</html>",
                            "Внимание!",
                            JOptionPane.YES_NO_OPTION,
                            JOptionPane.INFORMATION_MESSAGE) != 0) {
            return;
        }
        try {
            NetCommander.removeSession(netProperty, session.getUser().getId());
            sessionsListModel.removeElement(session);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                                          "Сессия не была удалена!",
                                          "Внимание!",
                                          JOptionPane.ERROR_MESSAGE);
        }
    }
    
