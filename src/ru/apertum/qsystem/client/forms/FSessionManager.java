    private void loadRelativeData() {
        try {
            sessionsListModel = new QSessionList(NetCommander.getSessions(netProperty));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                                          "Ошибка получения списка сессий",
                                          "Внимание!",
                                          JOptionPane.ERROR_MESSAGE);
        }
        jListSessions.setModel(sessionsListModel);
    }

